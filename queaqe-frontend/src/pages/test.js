import React, { useState, useEffect, useRef } from 'react';
import SockJS from 'sockjs-client';
import { Client } from '@stomp/stompjs';

const PrivateChat = () => {
  const [recipientId, setRecipientId] = useState('');
  const [messageContent, setMessageContent] = useState('');
  const [messages, setMessages] = useState([]);
  const stompClientRef = useRef(null);
  const jwtToken = localStorage.getItem('jwtToken');

  useEffect(() => {
    connect();

    return () => {
      if (stompClientRef.current?.connected) {
        stompClientRef.current.deactivate();
        console.log('Disconnected');
      }
    };
  }, []); // ✅ Removed senderId dependency

  const connect = () => {
    if (stompClientRef.current?.connected) {
      console.log('Already connected.');
      return;
    }

    const socket = new SockJS('http://localhost:8084/ws');

    stompClientRef.current = new Client({
      webSocketFactory: () => socket,
      connectHeaders: {
        'Authorization': `Bearer ${jwtToken}`
      },
      onConnect: (frame) => {
        console.log('✅ Connected:', frame);

        // Subscribe to personal user queue
        stompClientRef.current.subscribe('/user/queue/messages', (msg) => {
          const received = JSON.parse(msg.body);
          setMessages((prev) => [...prev, received]);
        });
      },
      onStompError: (frame) => {
        console.error('❌ STOMP error:', frame.headers['message']);
        console.error(frame.body);
      }
    });

    stompClientRef.current.activate();
  };

  const sendMessage = () => {
    if (!stompClientRef.current?.connected) {
      alert('Not connected. Please connect first.');
      return;
    }

    if (!recipientId || !messageContent) {
      alert('Please enter Recipient ID and message.');
      return;
    }

    const payload = {
      recipientId,
      content: messageContent
      // ⛔ senderId removed; backend gets it from JWT
      // ✅ conversationId can be generated by backend
    };

    stompClientRef.current.publish({
      destination: '/app/chat.sendMessage',
      body: JSON.stringify(payload)
    });

    setMessageContent('');
  };

  return (
    <div>
      <h2>Private Chat</h2>

      <div>
        <label>Recipient ID:</label>
        <input
          type="text"
          value={recipientId}
          onChange={(e) => setRecipientId(e.target.value)}
        />
      </div>

      <div>
        <label>Message:</label>
        <input
          type="text"
          value={messageContent}
          onChange={(e) => setMessageContent(e.target.value)}
        />
      </div>

      <button onClick={sendMessage}>Send</button>
      <button onClick={connect}>Connect</button>

      <h3>Messages:</h3>
      <ul>
        {messages.map((msg, index) => (
          <li key={index}>
            <b>{msg.senderId}</b>: {msg.content}
          </li>
        ))}
      </ul>
    </div>
  );
};

export default PrivateChat;
